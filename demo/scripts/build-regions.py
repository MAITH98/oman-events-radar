#!/usr/bin/env python3
"""
One-off build of app/features/twin/geo/regions.ts — Oman's governorates and Muscat's wilayats as simplified
polygons for the dotted venue map. Run by hand when boundaries change (needs network); the site never calls OSM.

  python3 scripts/build-regions.py

Data: © OpenStreetMap contributors (ODbL), via the Overpass API. Rings are assembled from the relations' outer
ways and simplified (Ramer–Douglas–Peucker) to keep the file small. Python standard library only.
"""
import json, time, urllib.parse, urllib.request
from pathlib import Path

API = "https://overpass-api.de/api/interpreter"
UA = "OmanEventsRadarDemo/1.0 (one-off basemap build; https://github.com/MAITH98/oman-events-radar)"
OUT = Path(__file__).resolve().parent.parent / "app/features/twin/geo/regions.ts"
MUSCAT_GOV = 3781239


def overpass(q: str) -> dict:
    for attempt in range(6):
        try:
            req = urllib.request.Request(API, data=urllib.parse.urlencode({"data": q}).encode(), headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=180) as r:
                return json.loads(r.read())
        except Exception as e:  # rate limits and timeouts: back off and retry
            print(f"  overpass retry {attempt + 1}: {e}")
            time.sleep(10 * (attempt + 1))
    raise SystemExit("Overpass unavailable")


def rings(rel: dict) -> list[list[tuple[float, float]]]:
    """Join a relation's outer ways end to end into closed rings."""
    ways = [[(p["lon"], p["lat"]) for p in m["geometry"]] for m in rel["members"] if m["type"] == "way" and m.get("role") in ("outer", "") and m.get("geometry")]
    out = []
    while ways:
        ring = ways.pop(0)
        changed = True
        while changed and ring[0] != ring[-1]:
            changed = False
            for i, w in enumerate(ways):
                if w[0] == ring[-1]: ring += w[1:]
                elif w[-1] == ring[-1]: ring += w[::-1][1:]
                elif w[-1] == ring[0]: ring = w + ring[1:]
                elif w[0] == ring[0]: ring = w[::-1] + ring[1:]
                else: continue
                ways.pop(i); changed = True; break
        if len(ring) > 3: out.append(ring)
    return out


def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = (dx * dx + dy * dy) ** 0.5 or 1e-12
    i, dmax = 0, 0.0
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / norm
        if d > dmax: i, dmax = k, d
    if dmax <= eps: return [pts[0], pts[-1]]
    return rdp(pts[: i + 1], eps)[:-1] + rdp(pts[i:], eps)


def simplify_ring(ring, eps):
    """RDP on a closed ring: its start and end coincide, so split it at the point farthest from the start first."""
    x0, y0 = ring[0]
    k = max(range(len(ring)), key=lambda i: (ring[i][0] - x0) ** 2 + (ring[i][1] - y0) ** 2)
    if k == 0: return ring
    return rdp(ring[: k + 1], eps)[:-1] + rdp(ring[k:], eps)


def regions(q: str, eps: float, min_pts: int = 4):
    data = overpass(q)
    out = []
    for rel in data["elements"]:
        t = rel.get("tags", {})
        polys = [[(round(x, 3), round(y, 3)) for x, y in simplify_ring(r, eps)] for r in rings(rel)]
        polys = [p for p in polys if len(p) >= min_pts]
        if polys:
            out.append({"id": rel["id"], "name": t.get("name:en") or t.get("name", ""), "nameAr": t.get("name:ar") or t.get("name", ""), "rings": polys})
    out.sort(key=lambda r: r["name"])
    return out


print("governorates…")
gov = regions('[out:json][timeout:170];area["ISO3166-1"="OM"][admin_level=2]->.om;rel(area.om)["boundary"="administrative"]["admin_level"="4"];out geom;', 0.02)
time.sleep(8)
print("Muscat wilayats…")
wil = regions(f'[out:json][timeout:170];rel({MUSCAT_GOV});map_to_area->.g;rel(area.g)["boundary"="administrative"]["admin_level"~"^(5|6)$"];out geom;', 0.003)

def ts(rs):
    return "[\n" + "".join(
        f'  {{ name: {json.dumps(r["name"])}, nameAr: {json.dumps(r["nameAr"], ensure_ascii=False)}, rings: {json.dumps([[list(p) for p in ring] for ring in r["rings"]], separators=(",", ":"))} }},\n'
        for r in rs) + "]"

OUT.write_text(
    "// GENERATED by scripts/build-regions.py — do not edit by hand.\n"
    "// © OpenStreetMap contributors (ODbL), via Overpass; outer rings simplified (RDP). Coordinates are [lon, lat].\n\n"
    "export interface Region { name: string; nameAr: string; rings: [number, number][][] }\n\n"
    f"/** Oman's governorates (admin level 4). */\nexport const GOVERNORATES: Region[] = {ts(gov)};\n\n"
    f"/** Muscat Governorate's wilayats. */\nexport const MUSCAT_WILAYATS: Region[] = {ts(wil)};\n",
    encoding="utf-8")
print(f"wrote {OUT} — {len(gov)} governorates, {len(wil)} wilayats, {OUT.stat().st_size // 1024} KB")
