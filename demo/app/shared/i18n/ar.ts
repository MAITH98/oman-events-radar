// Arabic counting words: 1 = singular, 2 = dual, 3–10 = plural, 11+ = singular accusative.
function count(n: number, one: string, two: string, few: string, many: string) {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

